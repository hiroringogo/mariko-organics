// Date/time formatting helpers
export const dayNames = {
  ja: ["日", "月", "火", "水", "木", "金", "土"],
  en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
} as const;

const monthNamesEn = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

export function formatMonth(m: number, lang: "ja" | "en") {
  return lang === "ja" ? `${m}月` : monthNamesEn[m - 1];
}

export function formatDateFull(dateStr: string, lang: "ja" | "en") {
  const d = new Date(dateStr + "T00:00:00");
  const m = d.getMonth() + 1;
  const day = d.getDate();
  const dow = dayNames[lang][d.getDay()];
  if (lang === "ja") return `${m}月${day}日（${dow}）`;
  return `${dow}, ${monthNamesEn[m - 1]} ${day}`;
}
